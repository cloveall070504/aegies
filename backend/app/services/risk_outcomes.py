def get_risk_outcome(description: str) -> dict | None:
    """根据风险点 description 获取具体后果与整改步骤。"""
    return _RISK_OUTCOMES.get(description)


def get_specific_consequence(description: str, fallback: str = "") -> str:
    """获取具体后果，无映射时返回 fallback。"""
    out = _RISK_OUTCOMES.get(description)
    return out["consequence"] if out else fallback


def get_specific_correction_steps(description: str) -> List[str]:
    """获取针对性整改步骤，无映射时返回空列表。"""
    out = _RISK_OUTCOMES.get(description)
    return list(out.get("correction_steps", [])) if out else []
